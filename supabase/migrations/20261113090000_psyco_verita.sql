-- ---------------------------------------------------------------------
-- CHE NE SAI?! – PSYCO: «VERITÀ O FALSITÀ».
--
-- Nuova famiglia di regole: chi conosce la regola sa QUANDO dire la verità e QUANDO mentire
-- (o come segnalarlo col corpo), e lo PSYCO deve capire il meccanismo.
-- Le impostazioni della stanza scelgono quali regole pescare dall'archivio:
-- «tutte» (predefinita), «classiche» oppure solo «verità o falsità» (psyco_rooms.settings.rules).
--
-- Solo cose NUOVE: una colonna con default e righe nuove (on conflict do nothing);
-- le cinque regole d'archivio già basate su verità e bugie passano alla famiglia «verita»
-- (solo la colonna nuova, il testo non si tocca). Idempotente: si può rilanciare.
-- ---------------------------------------------------------------------

alter table public.psyco_rules add column if not exists theme text not null default 'classica';
do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'psyco_rules_theme_check') then
    alter table public.psyco_rules add constraint psyco_rules_theme_check check (theme in ('classica', 'verita'));
  end if;
end $$;
comment on column public.psyco_rules.theme is 'Famiglia della regola: classica oppure verita (VERITÀ O FALSITÀ)';
create index if not exists psyco_rules_theme_idx on public.psyco_rules (theme, difficulty) where active;

